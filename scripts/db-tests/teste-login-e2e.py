import asyncio
from playwright.async_api import async_playwright
B="http://127.0.0.1:3100"
results=[]
def ok(c,m):
    r=("✓" if c else "✗")+" "+m; results.append(r); print(r, flush=True)
async def login(pg, email):
    await pg.goto(B+"/entrar", wait_until="load")
    await pg.fill("input[name=email]", email)
    await pg.click("button[type=submit]")
    await pg.wait_for_timeout(1800)
async def main():
    async with async_playwright() as p:
        b = await p.chromium.launch(executable_path="/usr/bin/google-chrome")
        # ---- Cliente ----
        c = await b.new_context(viewport={"width":390,"height":844}, is_mobile=True, has_touch=True)
        pg = await c.new_page(); errs=[]
        pg.on("pageerror", lambda e: errs.append(str(e)))
        await login(pg, "ninguem@teste.com")
        t = await pg.inner_text("body")
        ok("Não encontramos uma assinatura ativa" in t and "Assine agora" in t, "e-mail desconhecido: mensagem + link de compra")
        await pg.screenshot(path="/home/claude/shots/e2e-erro.png")
        await login(pg, "vencido@teste.com")
        ok("Não encontramos uma assinatura ativa" in await pg.inner_text("body"), "assinatura vencida: não entra")
        await login(pg, "admin@teste.com")
        ok("Não encontramos uma assinatura ativa" in await pg.inner_text("body"), "conta admin não entra só com e-mail")
        await login(pg, "  Cliente@Teste.com ")
        ok(pg.url.rstrip("/")==B, f"cliente entra só com e-mail (url={pg.url})")
        await pg.wait_for_timeout(800)
        ok("Lançamentos" in await pg.inner_text("body"), "home carregou após login")
        await pg.goto(B+"/dorama/amor-em-seul", wait_until="load"); await pg.wait_for_timeout(500)
        print("url antes do botão:", pg.url, flush=True)
        btn = pg.locator("button[aria-pressed]").first
        await btn.click(); await pg.wait_for_timeout(1200)
        await pg.goto(B+"/minha-lista", wait_until="load"); await pg.wait_for_timeout(800)
        ok("AMOR EM SEUL" in (await pg.inner_text("main")).upper(), "Minha Lista salvou no banco")
        await pg.goto(B+"/perfil", wait_until="load"); await pg.wait_for_timeout(800)
        t = await pg.inner_text("main")
        ok("Cliente Teste" in t and "Mensal" in t and "Ativo" in t, "perfil mostra nome, plano e status reais")
        await pg.screenshot(path="/home/claude/shots/e2e-perfil.png", full_page=True)
        await pg.goto(B+"/assistir/"+(await pg.evaluate("1")).__str__(), wait_until="load")
        await pg.goto(B+"/admin", wait_until="load"); await pg.wait_for_timeout(800)
        ok("/admin/entrar" in pg.url, f"cliente é barrado no painel (url={pg.url})")
        await pg.goto(B+"/entrar", wait_until="load")
        ok(pg.url.rstrip("/")==B, "logado em /entrar → vai para a home")
        await pg.goto(B+"/perfil", wait_until="load")
        await pg.click("text=Sair da conta"); await pg.wait_for_timeout(1200)
        ok("/entrar" in pg.url, "sair da conta funciona")
        await pg.goto(B+"/", wait_until="load")
        ok("/entrar" in pg.url, "depois de sair, home pede login de novo")
        # ---- Admin ----
        a = await b.new_context(viewport={"width":1440,"height":900})
        ap = await a.new_page()
        ap.on("pageerror", lambda e: errs.append(str(e)))
        await ap.goto(B+"/admin/entrar", wait_until="load")
        await ap.fill("input[name=email]","admin@teste.com"); await ap.fill("input[name=password]","errada")
        await ap.click("button[type=submit]"); await ap.wait_for_timeout(1200)
        ok("E-mail ou senha incorretos" in await ap.inner_text("body"), "senha errada recusada")
        await ap.fill("input[name=password]","senha123"); await ap.click("button[type=submit]"); await ap.wait_for_timeout(2000)
        ok(ap.url.endswith("/admin"), f"admin entra com senha (url={ap.url})")
        await ap.goto(B+"/admin/usuarios", wait_until="load"); await ap.wait_for_timeout(1000)
        t = await ap.inner_text("main")
        ok("cliente@teste.com" in t and "vencido@teste.com" in t and "Expirado" in t, "lista de usuários real (com status)")
        await ap.click("text=Liberar acesso"); await ap.wait_for_timeout(400)
        await ap.fill("input[type=email]","novo.cliente@teste.com")
        await ap.click("[role=dialog] button:has-text('Liberar acesso')"); await ap.wait_for_timeout(2500)
        t = await ap.inner_text("body")
        ok("novo.cliente@teste.com" in t, "‘Liberar acesso’ criou a conta e o acesso")
        await ap.screenshot(path="/home/claude/shots/e2e-admin-users.png")
        # vencido: renovar pela gaveta
        await ap.click("text=vencido@teste.com"); await ap.wait_for_timeout(500)
        await ap.click("text=+30 dias"); await ap.click("text=Salvar alterações"); await ap.wait_for_timeout(2000)
        await ap.screenshot(path="/home/claude/shots/e2e-drawer.png")
        await ap.keyboard.press("Escape")
        await ap.goto(B+"/admin/planos", wait_until="load"); await ap.wait_for_timeout(600)
        ok("Trimestral" in await ap.inner_text("main"), "planos reais no painel")
        # ---- novo cliente entra ----
        n = await b.new_context(); np_ = await n.new_page()
        await login(np_, "novo.cliente@teste.com")
        ok(np_.url.rstrip("/")==B, "cliente liberado pelo painel consegue entrar")
        v = await b.new_context(); vp = await v.new_page()
        await login(vp, "vencido@teste.com")
        ok(vp.url.rstrip("/")==B, "cliente renovado (+30 dias) volta a entrar")
        ok(not errs, f"sem erros no navegador {errs[:3]}")
        await b.close()
    pass
asyncio.run(main())
